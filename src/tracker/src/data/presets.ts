// Helper to compute realistic, naturally distributed timestamps across hours and minutes
function getDistributedTime(hoursAgo: number, minutesOffset: number = 0): string {
  const totalOffsetMs = (hoursAgo * 60 + minutesOffset) * 60 * 1000;
  return new Date(Date.now() - totalOffsetMs).toISOString();
}

